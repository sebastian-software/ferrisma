pub unsafe extern "C-unwind" fn av1_enable_segmentation(mut seg: *mut segmentation) {
    (*seg).enabled = 1 as uint8_t;
    (*seg).update_map = 1 as uint8_t;
    (*seg).update_data = 1 as uint8_t;
    (*seg).temporal_update = 0 as uint8_t;
}
#[no_mangle]
pub unsafe extern "C-unwind" fn av1_disable_segmentation(mut seg: *mut segmentation) {
    (*seg).enabled = 0 as uint8_t;
    (*seg).update_map = 0 as uint8_t;
    (*seg).update_data = 0 as uint8_t;
    (*seg).temporal_update = 0 as uint8_t;
}
#[no_mangle]
pub unsafe extern "C-unwind" fn av1_disable_segfeature(
    mut seg: *mut segmentation,
    mut segment_id: core::ffi::c_int,
    mut feature_id: SEG_LVL_FEATURES,
) {
    (*seg).feature_mask[segment_id as usize]
        &= !((1 as core::ffi::c_uint) << feature_id as core::ffi::c_int);
}
#[no_mangle]
pub unsafe extern "C-unwind" fn av1_clear_segdata(
    mut seg: *mut segmentation,
    mut segment_id: core::ffi::c_int,
    mut feature_id: SEG_LVL_FEATURES,
) {
    (*seg).feature_data[segment_id as usize][feature_id as usize] = 0 as int16_t;
}
#[no_mangle]
pub unsafe extern "C-unwind" fn av1_reset_segment_features(mut cm: *mut AV1_COMMON) {
    let mut seg: *mut segmentation = &raw mut (*cm).seg;
    (*seg).enabled = 0 as uint8_t;
    (*seg).update_map = 0 as uint8_t;
    (*seg).update_data = 0 as uint8_t;
    av1_clearall_segfeatures(seg);
}
