#!/usr/bin/env python3
"""Emit mechanical per-file selectors for the translated feature configurations."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONDITIONS = {
    "mini": 'all(feature = "mini", not(feature = "extended-pixi"))',
    "extended-pixi": 'all(not(feature = "mini"), feature = "extended-pixi")',
    "mini-extended-pixi": 'all(feature = "mini", feature = "extended-pixi")',
}
base = json.loads((ROOT / "TRANSLATION.json").read_text())["units"]
variants = {}
for name in CONDITIONS:
    path = ROOT / "translations" / f"{name}.json"
    if not path.exists():
        raise SystemExit(f"Translate {name} before generating feature selectors")
    variants[name] = {unit["source"]: unit for unit in json.loads(path.read_text())["units"]}

lines = ["// Generated by tools/update_modules.py; preserve configuration-specific C preprocessing."]
for unit in base:
    if unit["rust"].startswith("src/libyuv/"):
        continue
    for name, condition in CONDITIONS.items():
        alternative = variants[name][unit["source"]]["rust"]
        if alternative != unit["rust"]:
            lines.append(f'#[cfg_attr({condition}, path = "{alternative[4:]}")]')
    if Path(unit["rust"]).stem in ("scale", "reformat_libyuv") and (ROOT / "src/variants/libyuv" / Path(unit["rust"]).name).exists():
        lines.append(f'#[cfg_attr(feature = "libyuv", path = "variants/libyuv/{Path(unit["rust"]).name}")]')
    lines.append(f"pub mod {Path(unit['rust']).stem};")
    lines.append("")
lines += ['#[cfg(not(feature = "libyuv"))]', "pub mod libyuv {"]
for unit in base:
    if unit["rust"].startswith("src/libyuv/"):
        lines.append(f"    pub mod {Path(unit['rust']).stem};")
lines.append("}")
for feature in ["libgav1", "rav1e", "svt"]:
    lines += [f'#[cfg(feature = "{feature}")]', f'pub mod codec_{feature};']
(ROOT / "src/modules.rs").write_text("\n".join(lines) + "\n")
