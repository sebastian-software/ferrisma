// Genuine input generation through the original public encoder.

// An original profile generated by the original ColorEncoding/CMS code: P3
// primaries with a gamma transfer curve (gray: gamma only), so the embedded
// ICC differs from every enumerated sRGB default.
std::vector<uint8_t> IccProfile(bool gray) {
  JxlColorEncoding external;
  JxlColorEncodingSetToSRGB(&external, gray ? JXL_TRUE : JXL_FALSE);
  if (!gray) external.primaries = JXL_PRIMARIES_P3;
  external.transfer_function = JXL_TRANSFER_FUNCTION_GAMMA;
  external.gamma = 0.4;
  jxl::ColorEncoding c;
  if (!c.FromExternal(external)) throw std::runtime_error("icc encoding");
  if (c.ICC().empty() && !c.CreateICC()) throw std::runtime_error("icc profile");
  return c.ICC();
}

struct Spec {
  uint32_t xsize = 8, ysize = 8, channels = 3, alpha = 0, bits = 8;
  uint32_t extra = 0, orientation = 1, frames = 1, duration = 0;
  uint32_t container = 0, icc = 0, level = 0, index = 0, mode = 0;
  uint32_t lossless = 1, effort = 3, intrinsic = 0, premultiplied = 0;
  uint32_t gray_icc = 0, names = 0, timecodes = 0;
  std::vector<std::pair<std::string, std::pair<uint32_t, uint32_t>>> boxes;
  std::vector<uint32_t> box_after;  // 0: before frames, 1: after frames
};

Spec ParseSpec(std::istringstream& in) {
  Spec spec;
  std::string token;
  while (in >> token) {
    auto eq = token.find('=');
    if (eq == std::string::npos) throw std::runtime_error("encode spec");
    std::string key = token.substr(0, eq), value = token.substr(eq + 1);
    if (key == "box" || key == "late") {
      // box=TYPE:SIZE:COMPRESS
      auto c1 = value.find(':'), c2 = value.rfind(':');
      std::string type = value.substr(0, c1);
      while (type.size() < 4) type.push_back(' ');
      spec.boxes.push_back({type,
                            {uint32_t(std::stoul(value.substr(c1 + 1, c2 - c1 - 1))),
                             uint32_t(std::stoul(value.substr(c2 + 1)))}});
      spec.box_after.push_back(key == "late");
      continue;
    }
    uint32_t v = uint32_t(std::stoul(value));
    if (key == "w") spec.xsize = v;
    else if (key == "h") spec.ysize = v;
    else if (key == "c") spec.channels = v;
    else if (key == "a") spec.alpha = v;
    else if (key == "bits") spec.bits = v;
    else if (key == "ec") spec.extra = v;
    else if (key == "orient") spec.orientation = v;
    else if (key == "frames") spec.frames = v;
    else if (key == "duration") spec.duration = v;
    else if (key == "container") spec.container = v;
    else if (key == "icc") spec.icc = v;
    else if (key == "level") spec.level = v;
    else if (key == "index") spec.index = v;
    else if (key == "mode") spec.mode = v;
    else if (key == "lossless") spec.lossless = v;
    else if (key == "effort") spec.effort = v;
    else if (key == "intrinsic") spec.intrinsic = v;
    else if (key == "premul") spec.premultiplied = v;
    else if (key == "names") spec.names = v;
    else if (key == "timecodes") spec.timecodes = v;
    else throw std::runtime_error("encode spec key");
  }
  in.clear();
  return spec;
}

std::vector<uint8_t> Encode(const Spec& spec) {
  JxlEncoder* enc = JxlEncoderCreate(nullptr);
  if (!enc) throw std::runtime_error("encoder allocation");
  auto check = [&](JxlEncoderStatus status, const char* what) {
    if (status != JXL_ENC_SUCCESS) {
      JxlEncoderDestroy(enc);
      throw std::runtime_error(std::string("encoder: ") + what);
    }
  };
  check(JxlEncoderUseContainer(enc, spec.container ? JXL_TRUE : JXL_FALSE), "container");
  if (spec.level) check(JxlEncoderSetCodestreamLevel(enc, int(spec.level)), "level");
  JxlBasicInfo info;
  JxlEncoderInitBasicInfo(&info);
  info.xsize = spec.xsize;
  info.ysize = spec.ysize;
  info.bits_per_sample = spec.bits;
  info.num_color_channels = spec.channels;
  info.num_extra_channels = spec.alpha + spec.extra;
  info.alpha_bits = spec.alpha ? spec.bits : 0;
  info.alpha_premultiplied = spec.premultiplied ? JXL_TRUE : JXL_FALSE;
  info.orientation = JxlOrientation(spec.orientation);
  info.uses_original_profile = spec.lossless ? JXL_TRUE : JXL_FALSE;
  if (spec.intrinsic) {
    info.intrinsic_xsize = spec.xsize + 3;
    info.intrinsic_ysize = spec.ysize + 1;
  }
  if (spec.frames > 1 || spec.duration) {
    info.have_animation = JXL_TRUE;
    info.animation.tps_numerator = 100;
    info.animation.tps_denominator = 1;
    info.animation.num_loops = 2;
    info.animation.have_timecodes = spec.timecodes ? JXL_TRUE : JXL_FALSE;
  }
  check(JxlEncoderSetBasicInfo(enc, &info), "basic info");
  for (uint32_t i = 0; i < spec.extra; ++i) {
    JxlExtraChannelInfo ec;
    JxlEncoderInitExtraChannelInfo(i % 2 ? JXL_CHANNEL_SPOT_COLOR : JXL_CHANNEL_DEPTH, &ec);
    ec.bits_per_sample = spec.bits;
    if (ec.type == JXL_CHANNEL_SPOT_COLOR) {
      ec.spot_color[0] = 0.25f;
      ec.spot_color[1] = 0.5f;
      ec.spot_color[2] = 0.75f;
      ec.spot_color[3] = 0.5f;
    }
    check(JxlEncoderSetExtraChannelInfo(enc, spec.alpha + i, &ec), "extra info");
    if (spec.names) {
      std::string name = "channel" + std::to_string(i);
      check(JxlEncoderSetExtraChannelName(enc, spec.alpha + i, name.data(), name.size()),
            "extra name");
    }
  }
  JxlColorEncoding color;
  JxlColorEncodingSetToSRGB(&color, spec.channels == 1 ? JXL_TRUE : JXL_FALSE);
  if (spec.icc) {
    std::vector<uint8_t> icc = IccProfile(spec.channels == 1);
    check(JxlEncoderSetICCProfile(enc, icc.data(), icc.size()), "icc");
  } else {
    check(JxlEncoderSetColorEncoding(enc, &color), "color");
  }
  bool use_boxes = !spec.boxes.empty();
  if (use_boxes) check(JxlEncoderUseBoxes(enc), "use boxes");
  auto add_boxes = [&](uint32_t after) {
    for (size_t b = 0; b < spec.boxes.size(); ++b) {
      if (spec.box_after[b] != after) continue;
      const auto& box = spec.boxes[b];
      std::vector<uint8_t> contents(box.second.first);
      uint64_t seed = 0x9E3779B97F4A7C15ull + b;
      for (auto& v : contents) v = uint8_t(Next(seed) % 7 + 'a');
      if (box.first == "Exif" && contents.size() >= 4) {
        contents[0] = contents[1] = contents[2] = contents[3] = 0;
      }
      check(JxlEncoderAddBox(enc, box.first.data(), contents.data(), contents.size(),
                             box.second.second ? JXL_TRUE : JXL_FALSE),
            "box");
    }
  };
  add_boxes(0);
  JxlEncoderFrameSettings* settings = JxlEncoderFrameSettingsCreate(enc, nullptr);
  check(JxlEncoderFrameSettingsSetOption(settings, JXL_ENC_FRAME_SETTING_EFFORT, spec.effort),
        "effort");
  if (spec.lossless) check(JxlEncoderSetFrameLossless(settings, JXL_TRUE), "lossless");
  else check(JxlEncoderSetFrameDistance(settings, 1.5f), "distance");
  if (spec.index)
    check(JxlEncoderFrameSettingsSetOption(settings, JXL_ENC_FRAME_INDEX_BOX, 1), "index");
  if (spec.mode)
    check(JxlEncoderFrameSettingsSetOption(settings, JXL_ENC_FRAME_SETTING_OUTPUT_MODE,
                                           spec.mode),
          "mode");
  uint32_t colors = spec.channels + spec.alpha;
  JxlPixelFormat format{colors, spec.bits > 8 ? JXL_TYPE_UINT16 : JXL_TYPE_UINT8,
                        JXL_NATIVE_ENDIAN, 0};
  size_t sample = spec.bits > 8 ? 2 : 1;
  uint64_t seed = 0x1234567ull + spec.xsize * 31 + spec.ysize;
  for (uint32_t f = 0; f < spec.frames; ++f) {
    if (info.have_animation) {
      JxlFrameHeader header;
      JxlEncoderInitFrameHeader(&header);
      header.duration = spec.duration ? spec.duration : 1;
      header.timecode = f * 7;
      check(JxlEncoderSetFrameHeader(settings, &header), "frame header");
      if (spec.index && f == spec.frames - 1)
        check(JxlEncoderFrameSettingsSetOption(settings, JXL_ENC_FRAME_INDEX_BOX, 1), "index");
    }
    std::vector<uint8_t> pixels(size_t(spec.xsize) * spec.ysize * colors * sample);
    for (size_t i = 0; i < pixels.size(); ++i) {
      pixels[i] = uint8_t((i * 13 + f * 29 + (Next(seed) & 15)) & 0xff);
    }
    check(JxlEncoderAddImageFrame(settings, &format, pixels.data(), pixels.size()), "frame");
    for (uint32_t i = 0; i < spec.extra; ++i) {
      JxlPixelFormat ec_format{1, format.data_type, JXL_NATIVE_ENDIAN, 0};
      std::vector<uint8_t> plane(size_t(spec.xsize) * spec.ysize * sample);
      for (size_t j = 0; j < plane.size(); ++j) plane[j] = uint8_t((j * 5 + i * 3) & 0xff);
      check(JxlEncoderSetExtraChannelBuffer(settings, &ec_format, plane.data(), plane.size(),
                                            spec.alpha + i),
            "extra buffer");
    }
  }
  add_boxes(1);
  if (use_boxes) JxlEncoderCloseBoxes(enc);
  JxlEncoderCloseInput(enc);
  std::vector<uint8_t> output(4096);
  size_t size = 0;
  JxlEncoderStatus status;
  for (;;) {
    uint8_t* next = output.data() + size;
    size_t avail = output.size() - size;
    status = JxlEncoderProcessOutput(enc, &next, &avail);
    size = next - output.data();
    if (status != JXL_ENC_NEED_MORE_OUTPUT) break;
    output.resize(output.size() * 2);
  }
  JxlEncoderDestroy(enc);
  if (status != JXL_ENC_SUCCESS) throw std::runtime_error("encoder output");
  output.resize(size);
  return output;
}

