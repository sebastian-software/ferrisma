uint64_t Next(uint64_t& seed) {
  seed ^= seed << 13;
  seed ^= seed >> 7;
  seed ^= seed << 17;
  return seed;
}

std::string F32(float value) {
  uint32_t bits;
  memcpy(&bits, &value, 4);
  return std::to_string(bits);
}

std::string F64(double value) {
  uint64_t bits;
  memcpy(&bits, &value, 8);
  return std::to_string(bits);
}

