#!/usr/bin/env python3
"""Reproduce libaom's complete generic C archive with C2Rust 0.21.0."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys

from aom_compound_literals import name_float_tables
from aom_corrections import compatibility
from aom_api import facade
from aom_jumps import map_jumps
from build_aom import library_entries
from transpile_dav1d import corrected

ROOT = Path(__file__).resolve().parents[1]
CRATE = ROOT / 'crates/aom'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--release', action='store_true')
    parser.add_argument('--import-only', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--clang-include', type=Path)
    args = parser.parse_args()
    subprocess.run(['python3', ROOT / 'tools/verify_upstream.py'], check=True)
    profile = 'release' if args.release else 'debug'
    platform = 'linux' if sys.platform == 'linux' else 'macos'
    build = ROOT / f'build/aom-native-{profile}'
    entries = library_entries(build)
    if len(entries) != 168:
        raise SystemExit(f'Unexpected archive closure: {len(entries)}')
    work = ROOT / f'build/aom-translate/{profile}'
    work.mkdir(parents=True, exist_ok=True)
    resource = args.clang_include or (Path('/usr/lib/llvm-16/lib/clang/16/include') if platform == 'linux'
                else ROOT / 'build/toolchain/llvm@16/16.0.6_1/lib/clang/16/include')
    raw_root = ROOT / f'build/aom-generated/{profile}'
    raw_root.parent.mkdir(parents=True, exist_ok=True)
    environment = os.environ.copy()
    environment['DYLD_LIBRARY_PATH'] = os.environ.get('C2RUST_LIBRARY_PATH', str(resource.parents[2]) + ':/opt/homebrew/lib')
    inputs = []
    for original_entry in entries:
        entry = dict(original_entry)
        source = Path(entry['file'])
        original = source
        if source.name == 'tx_search.c':
            content, count = name_float_tables(source.read_text())
            source = work / 'tx_search.c'
            source.write_text(content)
            entry['command'] = entry['command'].replace(entry['file'], str(source))
            entry['file'] = str(source)
        entry['command'] += f' -isystem {resource}'
        inputs.append((original, source, entry))
    database = work / 'compile_commands.json'
    database.write_text(json.dumps([e for _, _, e in inputs], indent=2) + '\n')
    if not args.import_only:
        with (work / 'transpile.log').open('w') as log:
            result = subprocess.run(['c2rust-transpile', database, '--emit-build-files',
                                     '--fail-on-error', '--output-dir', raw_root],
                                    env=environment, stdout=log, stderr=subprocess.STDOUT)
        if result.returncode:
            raise SystemExit(f'C2Rust failed; inspect {work / "transpile.log"}')
    reference_files = {}
    for name in ['aom_config.h', 'aom_version.h', 'aom_dsp_rtcd.h', 'aom_scale_rtcd.h', 'av1_rtcd.h']:
        content = (build / 'config' / name).read_bytes()
        target = CRATE / f'reference/{platform}/{profile}/config' / name
        reference_files[f'config/{name}'] = hashlib.sha256(content).hexdigest()
        if args.check:
            if target.read_bytes() != content:
                raise SystemExit(f'Generated reference header differs: {name}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
    units, modules = [], ['// Generated by tools/transpile_aom.py.']
    ported_functions = set()
    for _, normalized, _ in inputs:
        relative = normalized.relative_to(ROOT / 'build').with_suffix('.rs')
        relative = Path(*(part.replace('-', '_') for part in relative.parts))
        raw = (raw_root / 'src' / relative).read_text()
        ported_functions.update(re.findall(r'pub unsafe extern "C" fn (\w+)\(', raw))
    if ported_functions & {'malloc', 'free', 'realloc', 'calloc', 'memcpy', 'memmove', 'memset', 'strlen'}:
        raise SystemExit('The codec source closure unexpectedly defines system runtime primitives')
    correction_version = hashlib.sha256(b''.join((ROOT / 'tools' / name).read_bytes() for name in
        ['transpile_dav1d.py', 'dav1d_layout.py', 'dav1d_storage.py', 'import_translation.py', 'check_abi.py'])
        + (ROOT / 'provenance/aom-source.json').read_bytes()
        + (build / 'config/aom_config.h').read_bytes()).hexdigest()
    for index, (original, normalized, entry) in enumerate(inputs):
        generated = original.is_relative_to(build)
        relative = original.relative_to(build if generated else ROOT / 'build/aom-native-source')
        relative = Path('generated') / relative if generated else relative
        source = CRATE / f'reference/{platform}/{profile}' / relative if generated else ROOT / 'upstream/aom' / relative
        if generated:
            source.parent.mkdir(parents=True, exist_ok=True)
            if args.check and source.read_bytes() != original.read_bytes():
                raise SystemExit(f'Generated C input changed: {relative}')
            if not args.check:
                source.write_bytes(original.read_bytes())
        raw_relative = normalized.relative_to(ROOT / 'build').with_suffix('.rs')
        raw_relative = Path(*(part.replace('-', '_') for part in raw_relative.parts))
        raw_path = raw_root / 'src' / raw_relative
        # An earlier single-unit diagnostic uses C2Rust's shorter common root.
        # Never fall back to another unit if the selected output is missing.
        raw = raw_path.read_text()
        cache = work / 'corrected-base' / relative.with_suffix('.json')
        key = hashlib.sha256((correction_version + raw + source.read_text() + json.dumps(entry, sort_keys=True)).encode()).hexdigest()
        cached = json.loads(cache.read_text()) if cache.exists() else {}
        if cached.get('key') == key and not args.check:
            text, changes = cached['text'], cached['changes']
        else:
            text, changes = corrected(source, raw, entry, allow_pruned_alignment=True)
            cache.parent.mkdir(parents=True, exist_ok=True)
            cache.write_text(json.dumps(dict(key=key, text=text, changes=changes)))
        text, jump_changes = map_jumps(text, ported_functions)
        changes.update(jump_changes)
        text, extra_changes = compatibility(text)
        changes.update(extra_changes)
        if original.name == 'tx_search.c':
            changes['name-static-float-compound-literals'] = 9
        text = text.replace('__dav1d_align_', '__aom_align_')
        target = CRATE / f'src/{platform}/{profile}' / relative.with_suffix('.rs')
        target.parent.mkdir(parents=True, exist_ok=True)
        if args.check:
            if target.read_text() != text:
                raise SystemExit(f'Translation differs: {target}')
        else:
            target.write_text(text)
        module = '__'.join(relative.with_suffix('').parts)
        modules.append(f'#[path = "{platform}/{profile}/{relative.with_suffix(".rs")}"] pub mod {module};')
        units.append(dict(source=str(source.relative_to(ROOT)), rust=str(target.relative_to(ROOT)),
                          raw_sha256=hashlib.sha256(raw.encode()).hexdigest(),
                          rust_sha256=hashlib.sha256(text.encode()).hexdigest(), corrections=changes))
        print(f'Imported {index + 1}/{len(inputs)}: {relative}', flush=True)
    for path, content in [
        (CRATE / f'src/modules-{platform}-{profile}.rs', '\n'.join(modules) + '\n'),
        (CRATE / f'src/api-{platform}-{profile}.rs', facade(units, build)),
        (CRATE / f'TRANSLATION-{platform}-{profile}.json', json.dumps(dict(
            translator='c2rust 0.21.0', llvm='16.0.6', preprocessing_profile=profile,
            generation_target='x86_64-unknown-linux-gnu' if platform == 'linux' else 'aarch64-apple-darwin',
            generated_reference_headers=reference_files, units=units), indent=2) + '\n')]:
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Inventory differs: {path}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
