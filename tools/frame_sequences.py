def sequence_variants(payload,header,ends):
    cases=[('complete',payload),('trailing',payload+b'\0'),('header-only',payload[:header])]
    start=header
    for end in ends:
        for cut in[start,start+(end-start)//2,end-1,end]:
            if cut<len(payload):cases.append((f'truncated-{cut}',payload[:cut]))
        broken=bytearray(payload);broken[end-1]^=0x80
        cases.append((f'xor80-{end-1}',bytes(broken)));start=end
    return cases


