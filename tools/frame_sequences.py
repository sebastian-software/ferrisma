def frame(w, h, **changes):
    result = dict(modular=1, type=0, dc=0, last=0, save=1, source=1, before=0,
                  blend=0, mode=2, clamp=1, x=0, y=0, w=w, h=h, duration=0,
                  timecode=0, seed=0, progressive=0, preview=0)
    if not changes.keys() <= result.keys():
        raise ValueError(changes)
    result.update(changes)
    return result


def encode_request(w, h, frames, gray=0, alpha=0, xyb=0, animation=0, preview=(0, 0)):
    fields = ['fs-encode', w, h, gray, alpha, xyb, animation, *preview, len(frames)]
    for item in frames:
        fields.extend(item.values())
    return ' '.join(map(str, fields))


