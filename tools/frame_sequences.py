def extended_encode_request(w,h,frames,main=1,ec=1,gray=0,alpha=0,xyb=0,animation=0,preview=(0,0)):
    fields=['fs-encode-ext',w,h,gray,alpha,xyb,animation,*preview,len(frames)]
    for item in frames:fields.extend([*item.values(),main,ec,1])
    return ' '.join(map(str,fields))


