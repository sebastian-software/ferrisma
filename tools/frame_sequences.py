def observe(binary, requests):
    result = subprocess.run([str(binary)], input='\n'.join(requests)+'\n',
                            text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(f'{binary} failed ({result.returncode}): {result.stderr}')
    if result.stderr:
        raise RuntimeError(f'Unexpected original stderr: {result.stderr}')
    lines=result.stdout.splitlines()
    if len(lines)!=len(requests):
        raise RuntimeError('Original sequence response count changed')
    return lines


def verify_writer_binding(build):
    """Relink identical objects with a temporary map; active graphs stay intact."""
    command=shlex.split((build/'CMakeFiles/jxl_oracle.dir/link.txt').read_text())
    obj='CMakeFiles/jxl_oracle.dir/frame_sequence_writes.cc.o'
    if command.count(obj)!=1:raise RuntimeError('Missing actual DC writer observation object')
    with tempfile.TemporaryDirectory(prefix='frame-sequence-bindings-') as directory:
        directory=Path(directory);mapping=directory/'selected.map'
        command[command.index('-o')+1]=str(directory/'selected')
        command.append('-Wl,-map,'+str(mapping) if sys.platform=='darwin' else '-Wl,-Map,'+str(mapping))
        subprocess.run(command,cwd=build,check=True)
        contents=mapping.read_text()
    names=['GetWriteToOutputStage','GetWriteToImageBundleStage','GetWriteToImage3FStage','FrameSequenceOriginalWriteToImage3FStage','FrameSequenceOriginalWriteToImageBundleStage']
    if sys.platform=='darwin':
        matches=re.findall(r'^\[\s*(\d+)\]\s+.*CMakeFiles/jxl_oracle.dir/frame_sequence_writes\.cc\.o$',contents,re.M)
        if len(matches)!=1:raise RuntimeError('Writer observation object absent from source map')
        source=matches[0]
        bound=[line for line in contents.splitlines() if re.search(r'\[\s*'+source+r'\]\s+',line) and 'FDE for:'not in line and any(re.search(r'_ZN3jxl[0-9]+'+name,line) for name in names)]
    else:
        bound=[];current=''
        for line in contents.splitlines():
            if 'CMakeFiles/jxl_oracle.dir/'in line and '.o'in line:current=line
            if re.search(r'^\s+0x[0-9a-f]+\s+',line) and any('jxl::'+name+'('in line for name in names):
                if obj not in current:raise RuntimeError('Actual writer bound outside pristine observation TU: '+line)
                bound.append(line)
    if len(bound)!=5 or any(not any(name in line for line in bound)for name in names):
        raise RuntimeError('Missing or duplicate actual writer factory bindings')
    print('All 5 actual public/original writer factories bind to the pristine forwarding TU',flush=True)
    return bound


