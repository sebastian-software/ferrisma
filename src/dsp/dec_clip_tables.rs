/// A pointer into the middle of a static table, indexed with signed offsets as
/// C indexes `VP8ksclip1` and its siblings. An index outside the table panics,
/// where C would read outside it. This type has no C counterpart.
#[derive(Clone, Copy, Debug)]
pub struct CenteredTable<T: 'static> {
    table: &'static [T],
    center: usize,
}

impl<T> Index<i32> for CenteredTable<T> {
    type Output = T;

    fn index(&self, index: i32) -> &T {
        let offset = isize::try_from(index).expect("an i32 fits in isize");
        let position = self
            .center
            .checked_add_signed(offset)
            .expect("index below the start of the table");
        &self.table[position]
    }
}

