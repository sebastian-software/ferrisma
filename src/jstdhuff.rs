// upstream: src/jstdhuff.c std_huff_tables
/// Sets up the standard Huffman tables (cf. JPEG standard section K.3) in the
/// slots that have none; valid only for 8-bit data precision.
///
/// # Errors
///
/// What `jpeg_alloc_huff_table` reports.
pub fn std_huff_tables(cinfo: j_common_ptr<'_, '_>) -> Result<(), ErrorExit> {
    add_huff_table(
        cinfo,
        |cinfo| &mut cinfo.dc_huff_tbl_ptrs[0],
        &bits_dc_luminance,
        &val_dc_luminance,
    )?;
    add_huff_table(
        cinfo,
        |cinfo| &mut cinfo.ac_huff_tbl_ptrs[0],
        &bits_ac_luminance,
        &val_ac_luminance,
    )?;
    add_huff_table(
        cinfo,
        |cinfo| &mut cinfo.dc_huff_tbl_ptrs[1],
        &bits_dc_chrominance,
        &val_dc_chrominance,
    )?;
    add_huff_table(
        cinfo,
        |cinfo| &mut cinfo.ac_huff_tbl_ptrs[1],
        &bits_ac_chrominance,
        &val_ac_chrominance,
    )?;
    Ok(())
}
