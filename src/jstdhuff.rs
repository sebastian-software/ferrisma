// upstream: src/jstdhuff.c add_huff_table
/// Defines a Huffman table, unless the decompressor already has one in that
/// slot; `htblptr` selects the slot, where C passes its address.
fn add_huff_table(
    cinfo: j_common_ptr<'_, '_>,
    htblptr: for<'a, 'b> fn(&'a mut jpeg_decompress_struct<'b>) -> &'a mut Option<Box<JHUFF_TBL>>,
    bits: &[UINT8; 17],
    val: &[UINT8],
) -> Result<(), ErrorExit> {
    if htblptr(cinfo).is_none() {
        let table = jpeg_alloc_huff_table(cinfo)?;
        *htblptr(cinfo) = Some(table);
    } else {
        // cinfo->is_decompressor is always TRUE (ADR 0005).
        return Ok(());
    }

    /* Copy the number-of-symbols-of-each-code-length counts */
    let htbl = htblptr(cinfo).as_mut().expect("allocated above");
    htbl.bits = *bits;

    /* Validate the counts.  We do this here mainly so we can copy the right
     * number of symbols from the val[] array, without risking marching off
     * the end of memory.  jchuff.c will do a more thorough test later.
     */
    let mut nsymbols: i32 = 0;
    for &count in &bits[1..=16] {
        nsymbols += i32::from(count);
    }
    if !(1..=256).contains(&nsymbols) {
        return Err(ERREXIT(cinfo, J_MESSAGE_CODE::JERR_BAD_HUFF_TABLE));
    }

    let nsymbols = nsymbols.unsigned_abs() as usize;
    let htbl = htblptr(cinfo).as_mut().expect("allocated above");
    htbl.huffval[..nsymbols].copy_from_slice(&val[..nsymbols]);
    htbl.huffval[nsymbols..].fill(0);

    /* Initialize sent_table FALSE so table will be written to JPEG file. */
    htbl.sent_table = false;
    Ok(())
}

