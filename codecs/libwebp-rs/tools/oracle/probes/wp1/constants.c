#define PRINT_INT(name) printf(#name "=%lld\n", (long long)(name))
#define PRINT_UINT(name) printf(#name "=%llu\n", (unsigned long long)(name))

static void PrintModePredicates(void) {
  int mode;
  for (mode = 0; mode < (int)MODE_LAST; ++mode) {
    const WEBP_CSP_MODE csp = (WEBP_CSP_MODE)mode;
    printf("WebPIsPremultipliedMode.%d=%d\n", mode, WebPIsPremultipliedMode(csp));
    printf("WebPIsAlphaMode.%d=%d\n", mode, WebPIsAlphaMode(csp));
    printf("WebPIsRGBMode.%d=%d\n", mode, WebPIsRGBMode(csp));
  }
}

static void PrintAbiChecks(void) {
  printf("WEBP_ABI_IS_INCOMPATIBLE.0x0210.0x0210=%d\n",
         WEBP_ABI_IS_INCOMPATIBLE(0x0210, 0x0210));
  printf("WEBP_ABI_IS_INCOMPATIBLE.0x0210.0x02ff=%d\n",
         WEBP_ABI_IS_INCOMPATIBLE(0x0210, 0x02ff));
  printf("WEBP_ABI_IS_INCOMPATIBLE.0x0210.0x0300=%d\n",
         WEBP_ABI_IS_INCOMPATIBLE(0x0210, 0x0300));
  printf("WEBP_ABI_IS_INCOMPATIBLE.0x0107.0x0109=%d\n",
         WEBP_ABI_IS_INCOMPATIBLE(0x0107, 0x0109));
  printf("WEBP_ABI_IS_INCOMPATIBLE.0x0100.0x0200=%d\n",
         WEBP_ABI_IS_INCOMPATIBLE(0x0100, 0x0200));
}

