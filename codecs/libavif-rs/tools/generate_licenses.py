#!/usr/bin/env python3
"""Generate crate-local upstream license material from verified provenance."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path in sorted((ROOT / "provenance").glob("*-source.json")):
        record = json.loads(path.read_text())
        crate = ROOT / record["crate"]
        notice = ["# Upstream attribution", "", "Generated by `tools/generate_licenses.py`.", "",
                  f"Component: {record['component']}", f"Source: {record['repository']}",
                  f"Revision: `{record['revision']}`", f"Primary license: {record['license']}", "",
                  "The original license, patent grant, and author notices are retained verbatim:", ""]
        outputs = {}
        for name in record["license_files"]:
            content = (ROOT / record["source_root"] / name).read_bytes()
            digest = hashlib.sha256(content).hexdigest()
            if digest != record["files"][name]:
                raise SystemExit(f"Upstream license differs: {name}")
            outputs[crate / "LICENSES" / name] = content
            notice.append(f"- `LICENSES/{name}` — SHA-256 `{digest}`")
        outputs[crate / "NOTICE.md"] = ("\n".join(notice) + "\n").encode()
        for target, content in outputs.items():
            if args.check:
                if not target.exists() or target.read_bytes() != content:
                    raise SystemExit(f"Regenerate license material: {target}")
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(content)
        print(f"{'Verified' if args.check else 'Generated'} license records for {record['component']}")


if __name__ == "__main__":
    main()
