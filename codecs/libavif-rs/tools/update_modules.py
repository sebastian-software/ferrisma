#!/usr/bin/env python3
"""Emit mechanical per-file selectors for the translated feature configurations."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONDITIONS = {
    "mini": 'all(feature = "mini", not(feature = "extended-pixi"), not(feature = "avm"))',
    "extended-pixi": 'all(not(feature = "mini"), feature = "extended-pixi", not(feature = "avm"))',
    "mini-extended-pixi": 'all(feature = "mini", feature = "extended-pixi", not(feature = "avm"))',
    "avm": 'all(not(feature = "mini"), not(feature = "extended-pixi"), feature = "avm")',
    "mini-avm": 'all(feature = "mini", not(feature = "extended-pixi"), feature = "avm")',
    "extended-pixi-avm": 'all(not(feature = "mini"), feature = "extended-pixi", feature = "avm")',
    "mini-extended-pixi-avm": 'all(feature = "mini", feature = "extended-pixi", feature = "avm")',
}
base = json.loads((ROOT / "TRANSLATION.json").read_text())["units"]
variants = {}
for name in CONDITIONS:
    path = ROOT / "translations" / f"{name}.json"
    if not path.exists():
        raise SystemExit(f"Translate {name} before generating feature selectors")
    variants[name] = {unit["source"]: unit for unit in json.loads(path.read_text())["units"]}

lines = ["// Generated by tools/update_modules.py; preserve configuration-specific C preprocessing."]
for unit in base:
    if unit["rust"].startswith("src/libyuv/"):
        continue
    if Path(unit["rust"]).stem == "read":
        # Compose the unchanged generated reader with the handwritten,
        # same-module sample access seam used by the Ferrixel input adapter.
        for name, condition in CONDITIONS.items():
            alternative = variants[name][unit["source"]]["rust"]
            lines += [f'#[cfg({condition})]', 'pub mod read {',
                      f'    include!(concat!(env!("CARGO_MANIFEST_DIR"), "/{alternative}"));',
                      '    include!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/read_sample_access.rs"));',
                      '}', '']
        lines += [f'#[cfg(not(any({", ".join(CONDITIONS.values())})))]', 'pub mod read {',
                  '    include!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/read.rs"));',
                  '    include!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/read_sample_access.rs"));',
                  '}', '']
        continue
    for name, condition in CONDITIONS.items():
        alternative = variants[name][unit["source"]]["rust"]
        if alternative != unit["rust"]:
            lines.append(f'#[cfg_attr({condition}, path = "{alternative[4:]}")]')
    if Path(unit["rust"]).stem in ("scale", "reformat_libyuv") and (ROOT / "src/variants/libyuv" / Path(unit["rust"]).name).exists():
        lines.append(f'#[cfg_attr(feature = "libyuv", path = "variants/libyuv/{Path(unit["rust"]).name}")]')
    lines.append(f"pub mod {Path(unit['rust']).stem};")
    lines.append("")
lines += ['#[cfg(not(feature = "libyuv"))]', "pub mod libyuv {"]
for unit in base:
    if unit["rust"].startswith("src/libyuv/"):
        lines.append(f"    pub mod {Path(unit['rust']).stem};")
lines.append("}")
for feature in ["libgav1", "rav1e", "svt", "avm"]:
    lines += [f'#[cfg(feature = "{feature}")]', f'pub mod codec_{feature};']
(ROOT / "src/modules.rs").write_text("\n".join(lines) + "\n")
