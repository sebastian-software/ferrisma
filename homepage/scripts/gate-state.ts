// The homepage's per-port gate state, generated from the table "Where each
// port stands (YYYY-MM-DD)" in docs/quality-gate.md, so the two cannot drift.
// The build fails when the table is missing or has another shape.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const homepage = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const guide = resolve(homepage, "../docs/quality-gate.md");
export const output = resolve(homepage, "app/gate-state.generated.ts");

const HEADER = [
  "Port",
  "In short",
  "AArch64: scalar and NEON",
  "x86-64: scalar, SSE levels and AVX2",
  "What is open",
];

/** The guide's port rows, in the order the homepage shows them, by format. */
const FORMATS: { format: string; rows: { port: string; label?: string }[] }[] = [
  { format: "JPEG", rows: [{ port: "libjpeg-turbo-rs" }] },
  { format: "WebP", rows: [{ port: "libwebp-rs" }] },
  {
    format: "JPEG XL",
    rows: [
      { port: "libjxl-rs decoder", label: "Decoder" },
      { port: "libjxl-rs encoder", label: "Encoder" },
    ],
  },
  { format: "AVIF", rows: [{ port: "libavif-rs with libaom" }] },
];

const MONTHS = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
];

export type GateState = { asOf: string; ports: { port: string; state: string }[] };

/** Markdown inline marks to plain text: code spans and links keep their words. */
function plain(cell: string): string {
  return cell
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replaceAll("`", "")
    .replace(/(\d{4})-(\d{2})-(\d{2})/g, (_, y: string, m: string, d: string) => {
      return `${MONTHS[Number(m) - 1]} ${Number(d)}`;
    })
    .trim();
}

function cells(line: string): string[] {
  if (!line.startsWith("|") || !line.endsWith("|")) throw Error(`Not a table row: ${line}`);
  return line
    .slice(1, -1)
    .split("|")
    .map((cell) => cell.trim());
}

export function parseGateState(markdown: string): GateState {
  const heading = /^## Where each port stands \((\d{4})-(\d{2})-(\d{2})\)$/m.exec(markdown);
  if (!heading) throw Error('quality-gate.md has no heading "Where each port stands (YYYY-MM-DD)"');
  const asOf = `${MONTHS[Number(heading[2]) - 1]} ${Number(heading[3])}, ${heading[1]}`;
  const rest = markdown.slice(heading.index + heading[0].length);
  const next = rest.search(/^## /m);
  const lines = (next < 0 ? rest : rest.slice(0, next))
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.startsWith("|"));
  if (lines.length < 3) throw Error("The table under Where each port stands is missing");
  const header = cells(lines[0]);
  if (header.join("|") !== HEADER.join("|"))
    throw Error(`Unexpected columns in Where each port stands: ${header.join(" | ")}`);
  const rows = new Map<string, string>();
  for (const line of lines.slice(2)) {
    const row = cells(line);
    if (row.length !== HEADER.length) throw Error(`Unexpected row shape: ${line}`);
    if (row[1].length === 0) throw Error(`Empty "In short" for ${row[0]}`);
    rows.set(row[0], plain(row[1]));
  }
  const known = new Set(FORMATS.flatMap((format) => format.rows.map((row) => row.port)));
  for (const port of rows.keys())
    if (!known.has(port)) throw Error(`Unknown port in Where each port stands: ${port}`);
  const ports = FORMATS.map(({ format, rows: wanted }) => {
    const parts = wanted.map(({ port, label }) => {
      const state = rows.get(port);
      if (state === undefined) throw Error(`Where each port stands has no row for ${port}`);
      return label === undefined ? state : `${label}: ${state}`;
    });
    return { port: format, state: parts.join(" ") };
  });
  return { asOf, ports };
}

export function writeGateState(): void {
  const state = parseGateState(readFileSync(guide, "utf8"));
  writeFileSync(
    output,
    `// Generated by scripts/gate-state.ts from docs/quality-gate.md. Do not edit.\n` +
      `export const GATE_AS_OF = ${JSON.stringify(state.asOf)};\n` +
      `export const GATE_STATE: { port: string; state: string }[] = ${JSON.stringify(state.ports, null, 2)};\n`,
  );
}
